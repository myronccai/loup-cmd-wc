#!/usr/bin/env python3
"""Writes source/commands/widths.loup: the display width of every Unicode
code point as glibc's wcwidth() reports it in a UTF-8 locale, which is what
GNU wc -L adds up. Run it on Linux with glibc and the en_US.UTF-8 locale:

    python3 tools/gen_widths.py > source/commands/widths.loup

The table is a list of runs (first code point, width), about 2,000 of them:
a new run starts wherever the width changes. Code points glibc does not know
(unassigned or surrogates) have width 0, as wcwidth() returns -1 for them.
"""

import ctypes
import ctypes.util
import platform

LC_ALL = 6
libc = ctypes.CDLL(ctypes.util.find_library("c"))
libc.setlocale.restype = ctypes.c_char_p
if not libc.setlocale(LC_ALL, b"en_US.UTF-8"):
    raise SystemExit("the en_US.UTF-8 locale is not installed")
libc.wcwidth.argtypes = [ctypes.c_uint32]

runs = []
for cp in range(0x110000):
    width = max(libc.wcwidth(cp), 0)
    if not runs or runs[-1][1] != width:
        runs.append((cp, width))

values = []
for first, width in runs:
    values.append("0x%X" % first)
    values.append(str(width))

print("@mode(host.dual)")
print()
print("# Display widths of Unicode code points, for wc -L. Generated by")
print("# tools/gen_widths.py from glibc %s's wcwidth() in en_US.UTF-8: do not edit."
      % platform.libc_ver()[1])
print("#")
print("# Runtime: host.dual. Data only, compiled into the native binary build/wc")
print("# by `make build`; `loup run source/main.loup` interprets the same code.")
print("#")
print("# Pairs of (first code point of a run, width of every code point in it),")
print("# in ascending order. Controls and code points glibc does not know have")
print("# width 0.")
print()
print("pub func width_runs(): list[int] {")
print("    return [")
for i in range(0, len(values), 12):
    print("        " + ", ".join(values[i:i + 12]) + ",")
print("    ];")
print("}")
